"""
Compare terminal-exon localization between conserved and lower-coverage
HERV-derived domain predictions.

Input
-----
domain_centered_unique_domains.tsv generated by
05_build_domain_centered_terminal_exon_table.py with --min-coverage 0.

Primary comparison
------------------
- Conserved: Coverage >= --coverage-threshold (default 0.40)
- Lower coverage: Coverage < --coverage-threshold
- Terminal: terminal in at least one qualifying transcript
- Non-terminal: non-terminal in all qualifying transcripts

Sensitivity analysis
--------------------
The same comparison restricted to domains with at least one qualifying
multi-exon transcript.
"""

from __future__ import annotations

import argparse
import hashlib
import math
import os
import shutil
import tempfile

import numpy as np
import pandas as pd
from scipy.stats import fisher_exact


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--domains",
        required=True,
        help="All-coverage domain_centered_unique_domains.tsv",
    )
    parser.add_argument("--outdir", required=True)
    parser.add_argument("--coverage-threshold", type=float, default=0.40)
    return parser.parse_args()


def odds_ratio_ci(a: int, b: int, c: int, d: int) -> tuple[float, float, float]:
    """Wald 95% CI for the odds ratio, with Haldane correction if needed."""
    values = np.array([a, b, c, d], dtype=float)
    if np.any(values == 0):
        values += 0.5
    aa, bb, cc, dd = values
    odds_ratio = (aa * dd) / (bb * cc)
    se = math.sqrt(1 / aa + 1 / bb + 1 / cc + 1 / dd)
    lower = math.exp(math.log(odds_ratio) - 1.96 * se)
    upper = math.exp(math.log(odds_ratio) + 1.96 * se)
    return float(odds_ratio), float(lower), float(upper)


def analyse(
    data: pd.DataFrame,
    analysis: str,
    terminal_column: str,
) -> tuple[list[dict], dict]:
    rows = []
    for group_name in ["conserved", "lower_coverage"]:
        group = data.loc[data["conservation_group"] == group_name]
        terminal = int(group[terminal_column].sum())
        nonterminal = int((~group[terminal_column]).sum())
        total = len(group)
        rows.append(
            {
                "analysis": analysis,
                "conservation_group": group_name,
                "terminal": terminal,
                "nonterminal": nonterminal,
                "total": total,
                "terminal_fraction": terminal / total if total else np.nan,
                "terminal_percent": 100 * terminal / total if total else np.nan,
            }
        )

    counts = {row["conservation_group"]: row for row in rows}
    a = counts["conserved"]["terminal"]
    b = counts["conserved"]["nonterminal"]
    c = counts["lower_coverage"]["terminal"]
    d = counts["lower_coverage"]["nonterminal"]

    table = np.array([[a, b], [c, d]], dtype=int)
    two_sided = fisher_exact(table, alternative="two-sided")
    greater = fisher_exact(table, alternative="greater")
    odds_ratio, ci_lower, ci_upper = odds_ratio_ci(a, b, c, d)

    result = {
        "analysis": analysis,
        "coverage_threshold": float(data.attrs["coverage_threshold"]),
        "conserved_terminal": a,
        "conserved_nonterminal": b,
        "lower_coverage_terminal": c,
        "lower_coverage_nonterminal": d,
        "conserved_terminal_fraction": a / (a + b),
        "lower_coverage_terminal_fraction": c / (c + d),
        "absolute_percentage_point_difference": 100 * (a / (a + b) - c / (c + d)),
        "odds_ratio": odds_ratio,
        "odds_ratio_95ci_lower": ci_lower,
        "odds_ratio_95ci_upper": ci_upper,
        "fisher_p_two_sided": float(two_sided.pvalue),
        "fisher_p_conserved_greater": float(greater.pvalue),
    }
    return rows, result


# RELEASE: accepted-input guard ----------------------------------------------------
def _release_guard_inputs(args: argparse.Namespace) -> None:
    p = os.path.abspath(args.domains)
    if os.path.basename(p) != "domain_centered_unique_domains.tsv" or os.path.basename(os.path.dirname(p)) != "all_coverage":
        raise ValueError("RELEASE: input must be the order-30 all_coverage domain_centered_unique_domains.tsv (D026)")
    d = os.path.dirname(os.path.dirname(p))
    rel = "./all_coverage/domain_centered_unique_domains.tsv"
    want = None
    for line in open(os.path.join(d, "checksums.sha256")):
        h, f = line.rstrip("\n").split(None, 1)
        if f in (rel, rel[2:]):
            want = h
    got = hashlib.sha256(open(p, "rb").read()).hexdigest()
    if want is None or got != want:
        raise ValueError("RELEASE: all_coverage unique-domain table does not match its accepted manifest")
    print(f"[RELEASE] {rel} sha256 {got} (manifest)", flush=True)


def main() -> int:
    args = parse_args()
    _release_guard_inputs(args)  # RELEASE
    final_outdir = args.outdir  # RELEASE: stage, publish atomically at the end
    parent = os.path.dirname(os.path.abspath(final_outdir)) or "."
    os.makedirs(parent, exist_ok=True)
    args.outdir = tempfile.mkdtemp(prefix=".stage_conservation.", dir=parent)
    os.makedirs(args.outdir, exist_ok=True)

    domains = pd.read_csv(args.domains, sep="\t")
    required = {
        "domain_uid",
        "Coverage",
        "domain_terminal_classification",
        "multi_exon_classification",
    }
    missing = sorted(required - set(domains.columns))
    if missing:
        raise ValueError("Missing required columns: " + ", ".join(missing))
    if domains["domain_uid"].duplicated().any():
        raise ValueError("domain_uid is not unique")

    domains["Coverage"] = pd.to_numeric(domains["Coverage"], errors="raise")
    domains["conservation_group"] = np.where(
        domains["Coverage"] >= args.coverage_threshold,
        "conserved",
        "lower_coverage",
    )
    domains["terminal_any"] = (
        domains["domain_terminal_classification"].astype(str) != "nonterminal_all"
    )

    multi = domains.loc[
        domains["multi_exon_classification"].astype(str) != "single_exon_only"
    ].copy()
    multi["terminal_any_multi_exon"] = (
        multi["multi_exon_classification"].astype(str)
        != "nonterminal_all_multi_exon"
    )
    multi.attrs["coverage_threshold"] = args.coverage_threshold
    domains.attrs["coverage_threshold"] = args.coverage_threshold

    # Re-run the primary analysis after setting attrs used in the output.
    domain_rows, domain_result = analyse(
        data=domains,
        analysis="all_qualifying_domains_terminal_in_any_transcript",
        terminal_column="terminal_any",
    )
    multi_rows, multi_result = analyse(
        data=multi,
        analysis="multi_exon_domains_terminal_in_any_transcript",
        terminal_column="terminal_any_multi_exon",
    )

    contingency = pd.DataFrame(domain_rows + multi_rows)
    tests = pd.DataFrame([domain_result, multi_result])

    contingency_path = os.path.join(
        args.outdir, "conservation_terminal_exon_contingency.tsv"
    )
    tests_path = os.path.join(
        args.outdir, "conservation_terminal_exon_fisher.tsv"
    )
    qc_path = os.path.join(args.outdir, "conservation_terminal_exon_qc.tsv")

    contingency.to_csv(contingency_path, sep="\t", index=False)
    tests.to_csv(tests_path, sep="\t", index=False)

    qc = pd.DataFrame(
        {
            "metric": [
                "input_unique_domains",
                "conserved_domains",
                "lower_coverage_domains",
                "multi_exon_domains",
                "conserved_multi_exon_domains",
                "lower_coverage_multi_exon_domains",
                "minimum_coverage",
                "maximum_coverage",
                "coverage_threshold",
            ],
            "value": [
                len(domains),
                int((domains["conservation_group"] == "conserved").sum()),
                int((domains["conservation_group"] == "lower_coverage").sum()),
                len(multi),
                int((multi["conservation_group"] == "conserved").sum()),
                int((multi["conservation_group"] == "lower_coverage").sum()),
                float(domains["Coverage"].min()),
                float(domains["Coverage"].max()),
                args.coverage_threshold,
            ],
        }
    )
    qc.to_csv(qc_path, sep="\t", index=False)

    # RELEASE: atomic publication of the staged directory
    for name in os.listdir(args.outdir):
        os.chmod(os.path.join(args.outdir, name), 0o644)
    if os.path.exists(final_outdir):
        shutil.rmtree(final_outdir)
    os.rename(args.outdir, final_outdir)
    os.chmod(final_outdir, 0o755)
    contingency_path, tests_path, qc_path = (
        os.path.join(final_outdir, os.path.basename(x)) for x in (contingency_path, tests_path, qc_path))

    print("\n=== CONSERVATION VS TERMINAL-EXON COMPARISON ===")
    print(contingency.to_string(index=False))
    print("\n=== FISHER EXACT TESTS ===")
    print(tests.to_string(index=False))
    print("\nOutputs:")
    print(f"  {contingency_path}")
    print(f"  {tests_path}")
    print(f"  {qc_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
