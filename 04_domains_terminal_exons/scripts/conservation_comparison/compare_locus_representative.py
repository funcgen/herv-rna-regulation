"""
Locus-level sensitivity analysis for the association between HMM profile
coverage and terminal-exon localization.

Purpose
-------
The domain-level comparison treats every predicted HERV-derived domain as one
observation. Because several domains can arise from the same HERV insertion,
this script repeats the comparison using one representative domain per HERV
locus.

Representative-domain rule
--------------------------
For each value of the `Locus` column:
  1. Select the domain with the highest HMM profile Coverage.
  2. If several domains have exactly the same Coverage, break the tie
     deterministically using domain_uid in lexicographic order.

The tie-break rule does not use terminal-exon status.

Primary comparison
------------------
- Conserved locus representative: Coverage >= --coverage-threshold
- Lower-coverage locus representative: Coverage < --coverage-threshold
- Terminal: representative domain is terminal in at least one qualifying
  transcript
- Non-terminal: representative domain is non-terminal in all qualifying
  transcripts

Sensitivity analysis
--------------------
Repeat the comparison among representatives with at least one qualifying
multi-exon transcript.

Input
-----
The all-coverage `domain_centered_unique_domains.tsv` generated by
05_build_domain_centered_terminal_exon_table.py with `--min-coverage 0`.

Outputs
-------
- locus_representative_domains.tsv
- locus_conservation_terminal_exon_contingency.tsv
- locus_conservation_terminal_exon_fisher.tsv
- locus_conservation_terminal_exon_qc.tsv
"""

from __future__ import annotations

import argparse
import hashlib
import math
import os
import shutil
import tempfile

import numpy as np
import pandas as pd
from scipy.stats import fisher_exact


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Repeat the conservation-versus-terminal-exon comparison using one "
            "highest-coverage representative domain per HERV locus."
        )
    )
    parser.add_argument(
        "--domains",
        required=True,
        help=(
            "All-coverage domain_centered_unique_domains.tsv generated with "
            "--min-coverage 0"
        ),
    )
    parser.add_argument("--outdir", required=True)
    parser.add_argument("--coverage-threshold", type=float, default=0.40)
    return parser.parse_args()


def as_bool(series: pd.Series) -> pd.Series:
    if pd.api.types.is_bool_dtype(series):
        return series.fillna(False)
    return (
        series.astype(str)
        .str.strip()
        .str.lower()
        .isin({"true", "t", "1", "yes"})
    )


def odds_ratio_ci(a: int, b: int, c: int, d: int) -> tuple[float, float, float]:
    """
    Wald 95% confidence interval for the odds ratio.

    A Haldane-Anscombe correction of 0.5 is applied only if a cell is zero.
    Fisher's exact test itself always uses the original integer counts.
    """
    values = np.array([a, b, c, d], dtype=float)
    if np.any(values == 0):
        values += 0.5

    aa, bb, cc, dd = values
    odds_ratio = (aa * dd) / (bb * cc)
    standard_error = math.sqrt(1 / aa + 1 / bb + 1 / cc + 1 / dd)
    lower = math.exp(math.log(odds_ratio) - 1.96 * standard_error)
    upper = math.exp(math.log(odds_ratio) + 1.96 * standard_error)
    return float(odds_ratio), float(lower), float(upper)


def select_representatives(domains: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    Select one highest-coverage domain per HERV locus.

    Returns
    -------
    representatives
        One row per locus.
    locus_diagnostics
        One row per locus with the number of domains and whether the maximum
        coverage was tied.
    """
    ordered = domains.sort_values(
        ["Locus", "Coverage", "domain_uid"],
        ascending=[True, False, True],
        kind="mergesort",
    ).copy()

    locus_diagnostics = (
        ordered.groupby("Locus", sort=False)
        .agg(
            n_domains_at_locus=("domain_uid", "size"),
            maximum_coverage=("Coverage", "max"),
        )
        .reset_index()
    )

    top_tie_counts = (
        ordered.merge(
            locus_diagnostics[["Locus", "maximum_coverage"]],
            on="Locus",
            how="left",
            validate="many_to_one",
        )
        .assign(
            is_maximum_coverage=lambda x: np.isclose(
                x["Coverage"], x["maximum_coverage"], rtol=0, atol=1e-12
            )
        )
        .groupby("Locus", sort=False)["is_maximum_coverage"]
        .sum()
        .astype(int)
        .rename("n_domains_tied_for_maximum_coverage")
        .reset_index()
    )

    locus_diagnostics = locus_diagnostics.merge(
        top_tie_counts,
        on="Locus",
        how="left",
        validate="one_to_one",
    )
    locus_diagnostics["maximum_coverage_is_tied"] = (
        locus_diagnostics["n_domains_tied_for_maximum_coverage"] > 1
    )

    representatives = (
        ordered.drop_duplicates("Locus", keep="first")
        .copy()
        .merge(
            locus_diagnostics,
            on="Locus",
            how="left",
            validate="one_to_one",
        )
    )

    return representatives, locus_diagnostics


def analyse(
    data: pd.DataFrame,
    analysis: str,
    terminal_column: str,
    coverage_threshold: float,
) -> tuple[list[dict], dict]:
    rows: list[dict] = []

    for group_name in ["conserved", "lower_coverage"]:
        group = data.loc[data["conservation_group"] == group_name].copy()
        terminal = int(group[terminal_column].sum())
        nonterminal = int((~group[terminal_column]).sum())
        total = int(len(group))

        rows.append(
            {
                "analysis": analysis,
                "conservation_group": group_name,
                "terminal": terminal,
                "nonterminal": nonterminal,
                "total": total,
                "terminal_fraction": terminal / total if total else np.nan,
                "terminal_percent": 100 * terminal / total if total else np.nan,
            }
        )

    counts = {row["conservation_group"]: row for row in rows}

    a = counts["conserved"]["terminal"]
    b = counts["conserved"]["nonterminal"]
    c = counts["lower_coverage"]["terminal"]
    d = counts["lower_coverage"]["nonterminal"]

    if (a + b) == 0 or (c + d) == 0:
        raise ValueError(
            f"Both conservation groups must contain at least one locus for {analysis}"
        )

    table = np.array([[a, b], [c, d]], dtype=int)
    fisher_two_sided = fisher_exact(table, alternative="two-sided")
    fisher_greater = fisher_exact(table, alternative="greater")
    odds_ratio, ci_lower, ci_upper = odds_ratio_ci(a, b, c, d)

    result = {
        "analysis": analysis,
        "coverage_threshold": coverage_threshold,
        "conserved_terminal": a,
        "conserved_nonterminal": b,
        "lower_coverage_terminal": c,
        "lower_coverage_nonterminal": d,
        "conserved_terminal_fraction": a / (a + b),
        "lower_coverage_terminal_fraction": c / (c + d),
        "absolute_percentage_point_difference": 100
        * (a / (a + b) - c / (c + d)),
        "odds_ratio": odds_ratio,
        "odds_ratio_95ci_lower": ci_lower,
        "odds_ratio_95ci_upper": ci_upper,
        "fisher_p_two_sided": float(fisher_two_sided.pvalue),
        "fisher_p_conserved_greater": float(fisher_greater.pvalue),
    }
    return rows, result


# RELEASE: accepted-input guard ----------------------------------------------------
def _release_guard_inputs(args: argparse.Namespace) -> None:
    p = os.path.abspath(args.domains)
    if os.path.basename(p) != "domain_centered_unique_domains.tsv" or os.path.basename(os.path.dirname(p)) != "all_coverage":
        raise ValueError("RELEASE: input must be the order-30 all_coverage domain_centered_unique_domains.tsv (D026)")
    d = os.path.dirname(os.path.dirname(p))
    rel = "./all_coverage/domain_centered_unique_domains.tsv"
    want = None
    for line in open(os.path.join(d, "checksums.sha256")):
        h, f = line.rstrip("\n").split(None, 1)
        if f in (rel, rel[2:]):
            want = h
    got = hashlib.sha256(open(p, "rb").read()).hexdigest()
    if want is None or got != want:
        raise ValueError("RELEASE: all_coverage unique-domain table does not match its accepted manifest")
    print(f"[RELEASE] {rel} sha256 {got} (manifest)", flush=True)


def main() -> int:
    args = parse_args()
    _release_guard_inputs(args)  # RELEASE
    final_outdir = args.outdir  # RELEASE: stage, publish atomically at the end
    parent = os.path.dirname(os.path.abspath(final_outdir)) or "."
    os.makedirs(parent, exist_ok=True)
    args.outdir = tempfile.mkdtemp(prefix=".stage_locus_representative.", dir=parent)

    if not 0 <= args.coverage_threshold <= 1:
        raise ValueError("--coverage-threshold must be between 0 and 1")

    os.makedirs(args.outdir, exist_ok=True)

    domains = pd.read_csv(args.domains, sep="\t")
    required_columns = {
        "domain_uid",
        "Locus",
        "Coverage",
        "domain_terminal_classification",
        "multi_exon_classification",
        "terminal_in_any_qualifying_transcript",
    }
    missing = sorted(required_columns - set(domains.columns))
    if missing:
        raise ValueError("Missing required columns: " + ", ".join(missing))

    if domains["domain_uid"].duplicated().any():
        raise ValueError("domain_uid is not unique")
    if domains["Locus"].isna().any() or (domains["Locus"].astype(str).str.strip() == "").any():
        raise ValueError("The Locus column contains missing or empty values")

    domains["Coverage"] = pd.to_numeric(domains["Coverage"], errors="raise")
    domains["terminal_in_any_qualifying_transcript"] = as_bool(
        domains["terminal_in_any_qualifying_transcript"]
    )

    representatives, locus_diagnostics = select_representatives(domains)

    representatives["conservation_group"] = np.where(
        representatives["Coverage"] >= args.coverage_threshold,
        "conserved",
        "lower_coverage",
    )
    representatives["terminal_any"] = (
        representatives["domain_terminal_classification"].astype(str)
        != "nonterminal_all"
    )

    consistency = (
        representatives["terminal_any"]
        == representatives["terminal_in_any_qualifying_transcript"]
    )
    if not consistency.all():
        raise ValueError(
            "Inconsistent terminal classification in representative-domain table"
        )

    representatives["has_qualifying_multi_exon_transcript"] = (
        representatives["multi_exon_classification"].astype(str)
        != "single_exon_only"
    )
    representatives["terminal_any_multi_exon"] = np.where(
        representatives["has_qualifying_multi_exon_transcript"],
        representatives["multi_exon_classification"].astype(str)
        != "nonterminal_all_multi_exon",
        False,
    )

    contingency_rows: list[dict] = []
    test_rows: list[dict] = []

    primary_rows, primary_result = analyse(
        data=representatives,
        analysis="one_representative_domain_per_locus_terminal_in_any_transcript",
        terminal_column="terminal_any",
        coverage_threshold=args.coverage_threshold,
    )
    contingency_rows.extend(primary_rows)
    test_rows.append(primary_result)

    multi = representatives.loc[
        representatives["has_qualifying_multi_exon_transcript"]
    ].copy()
    multi_rows, multi_result = analyse(
        data=multi,
        analysis=(
            "one_representative_domain_per_locus_"
            "multi_exon_terminal_in_any_transcript"
        ),
        terminal_column="terminal_any_multi_exon",
        coverage_threshold=args.coverage_threshold,
    )
    contingency_rows.extend(multi_rows)
    test_rows.append(multi_result)

    contingency = pd.DataFrame(contingency_rows)
    tests = pd.DataFrame(test_rows)

    representative_path = os.path.join(
        args.outdir, "locus_representative_domains.tsv"
    )
    contingency_path = os.path.join(
        args.outdir, "locus_conservation_terminal_exon_contingency.tsv"
    )
    tests_path = os.path.join(
        args.outdir, "locus_conservation_terminal_exon_fisher.tsv"
    )
    qc_path = os.path.join(
        args.outdir, "locus_conservation_terminal_exon_qc.tsv"
    )

    representatives.sort_values(
        ["chrom", "start", "end", "Locus"],
        kind="mergesort",
    ).to_csv(representative_path, sep="\t", index=False)
    contingency.to_csv(contingency_path, sep="\t", index=False)
    tests.to_csv(tests_path, sep="\t", index=False)

    qc = pd.DataFrame(
        {
            "metric": [
                "input_unique_domains",
                "input_unique_herv_loci",
                "selected_representative_domains",
                "loci_with_more_than_one_domain",
                "loci_with_tied_maximum_coverage",
                "maximum_domains_at_one_locus",
                "coverage_threshold",
                "conserved_representative_loci",
                "lower_coverage_representative_loci",
                "representative_loci_with_multi_exon_transcript",
                "conserved_multi_exon_representative_loci",
                "lower_coverage_multi_exon_representative_loci",
                "minimum_representative_coverage",
                "maximum_representative_coverage",
            ],
            "value": [
                len(domains),
                domains["Locus"].nunique(),
                len(representatives),
                int((locus_diagnostics["n_domains_at_locus"] > 1).sum()),
                int(locus_diagnostics["maximum_coverage_is_tied"].sum()),
                int(locus_diagnostics["n_domains_at_locus"].max()),
                args.coverage_threshold,
                int((representatives["conservation_group"] == "conserved").sum()),
                int((representatives["conservation_group"] == "lower_coverage").sum()),
                len(multi),
                int((multi["conservation_group"] == "conserved").sum()),
                int((multi["conservation_group"] == "lower_coverage").sum()),
                float(representatives["Coverage"].min()),
                float(representatives["Coverage"].max()),
            ],
        }
    )
    qc.to_csv(qc_path, sep="\t", index=False)

    # RELEASE: atomic publication of the staged directory
    for name in os.listdir(args.outdir):
        os.chmod(os.path.join(args.outdir, name), 0o644)
    if os.path.exists(final_outdir):
        shutil.rmtree(final_outdir)
    os.rename(args.outdir, final_outdir)
    os.chmod(final_outdir, 0o755)
    representative_path, contingency_path, tests_path, qc_path = (
        os.path.join(final_outdir, os.path.basename(x)) for x in (representative_path, contingency_path, tests_path, qc_path))

    print("\n=== ONE REPRESENTATIVE DOMAIN PER HERV LOCUS ===")
    print(contingency.to_string(index=False))

    print("\n=== LOCUS-LEVEL FISHER EXACT TESTS ===")
    print(tests.to_string(index=False))

    print("\n=== QC ===")
    print(qc.to_string(index=False))

    print("\nOutputs:")
    print(f"  {representative_path}")
    print(f"  {contingency_path}")
    print(f"  {tests_path}")
    print(f"  {qc_path}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
