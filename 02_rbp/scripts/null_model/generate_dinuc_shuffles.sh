#!/usr/bin/env bash
# =============================================================================
# 02_rbp / null_model : generate the dinucleotide-preserving shuffled controls
# =============================================================================
#   01_sources/frozen/herv/HERV_internal_sequences_v5.fasta   53,176 records
#     -> seeded Eulerian-trail shuffle (D002, D005)
#     -> results/null_model/fasta/HERV_internal_sequences_dinuc_shuffle_NN.fasta
#
# Replicate -> seed mapping is read from config/parameters.yaml and is explicit;
# it is never derived from the SLURM array index alone.
#
# Usage:  ./generate_dinuc_shuffles.sh [--replicate NN] [--out-dir DIR] [--force]
#         (no --replicate = all five)
# =============================================================================
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${HERE}/../../../config/lib/common.sh"

MODULE_DIR="${RELEASE_ROOT}/02_rbp"
PARAMS="${RELEASE_ROOT}/config/parameters.yaml"
IN_FASTA="${SOURCES_DIR}/frozen/herv/HERV_internal_sequences_v5.fasta"
OUT_DIR="${MODULE_DIR}/results/null_model/fasta"
REPLICATES=""
FORCE=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --replicate) REPLICATES="$2"; shift 2 ;;
    --out-dir)   OUT_DIR="$2";    shift 2 ;;
    --force)     FORCE=1;         shift ;;
    *) die "unknown argument: $1" ;;
  esac
done

mkdir -p "$OUT_DIR" "${MODULE_DIR}/logs"
export NCRNA_LOG_FILE="${MODULE_DIR}/logs/dinuc_shuffles.$(date +%Y%m%dT%H%M%S).log"

# --- scientific parameters, from config only ---------------------------------
# A small reader lives in its own file rather than inline: embedding shell
# variables into a regex inside a double-quoted python -c string is how "$(" in
# a pattern becomes a command substitution.
read_param() { python3 "${HERE}/read_config.py" --file "$PARAMS" --key "$1"; }
seed_for()   { python3 "${HERE}/read_config.py" --file "$PARAMS" --seed-for "$1"; }

BASE_SEED="$(read_param dinuc_shuffle_base_seed)"
LINE_WIDTH="$(read_param dinuc_shuffle_line_width)"
EXP_RECORDS="$(read_param dinuc_shuffle_expected_records)"
EXP_BASES="$(read_param dinuc_shuffle_expected_bases)"
N_SHUFFLES="$(read_param n_dinuc_shuffles)"

[[ -n "$BASE_SEED" && -n "$LINE_WIDTH" && -n "$EXP_RECORDS" && -n "$EXP_BASES" ]] \
  || die "could not read the dinuc shuffle parameters from ${PARAMS}"

# Not seq -w: it pads to the width of the largest value, so "seq -w 1 5"
# gives 1..5. The loop below reformats each entry with printf anyway.
[[ -n "$REPLICATES" ]] || REPLICATES="$(seq 1 "$N_SHUFFLES")"

# --- input identity ----------------------------------------------------------
[[ -f "$IN_FASTA" ]] || die "canonical HERV FASTA missing: ${IN_FASTA}
     Run 01_sources acquisition and verify_sources.sh first."

# The expected checksum comes from the 01_sources manifest, not from a literal
# here: 01_sources owns source identity, and a constant copied into this script
# would be a second place to update.
MANIFEST="${SOURCES_DIR}/manifests/upstream_releases.tsv"
EXPECTED_MD5="$(awk -F'\t' '$4 == "HERV_internal_sequences_v5.fasta" {print $5; exit}' "$MANIFEST")"
[[ -n "$EXPECTED_MD5" ]] \
  || die "HERV_internal_sequences_v5.fasta has no entry in ${MANIFEST}"
log "verifying canonical input FASTA against ${MANIFEST}"
verify_md5 "$IN_FASTA" "$EXPECTED_MD5"

log "system=${NCRNA_SYSTEM} release_root=${RELEASE_ROOT}"
log "input      = ${IN_FASTA}"
log "out dir    = ${OUT_DIR}"
log "base seed  = ${BASE_SEED}  line width = ${LINE_WIDTH}"

for rep in $REPLICATES; do
  rep="$(printf '%02d' "$((10#$rep))")"
  seed="$(seed_for "$rep")"
  [[ -n "$seed" ]] || die "no seed configured for replicate ${rep} in ${PARAMS}"

  # The two independent statements of the mapping must agree. If a launcher is
  # ever renumbered, this is what stops a replicate silently changing identity.
  derived="$(( BASE_SEED + 10#$rep ))"
  [[ "$seed" == "$derived" ]] \
    || die "seed mapping conflict for replicate ${rep}: config table says ${seed}, base_seed+${rep} gives ${derived}"

  out="${OUT_DIR}/HERV_internal_sequences_dinuc_shuffle_${rep}.fasta"
  tag="__dinuc_shuf${rep}"

  # Concurrency guard: two jobs targeting one replicate would race on the same
  # staging path. (Stage 1/2 lesson.)
  lock="${OUT_DIR}/.${rep}.lock"
  exec {lockfd}>"$lock"
  flock -n "$lockfd" || die "replicate ${rep} is already being generated by another process"

  if [[ -f "$out" && "$FORCE" -eq 0 ]]; then
    records="$(grep -c '^>' "$out" || true)"
    if [[ "$records" == "$EXP_RECORDS" ]]; then
      log "replicate ${rep}: already present with ${EXP_RECORDS} records; skipping"
      exec {lockfd}>&-
      continue
    fi
    log "replicate ${rep}: existing file has ${records} records; regenerating"
  fi

  log "replicate ${rep}: seed ${seed} -> ${out}"
  python3 "${HERE}/make_dinuc_shuffles.py" \
    --input  "$IN_FASTA" \
    --output "$out" \
    --seed   "$seed" \
    --tag    "$tag" \
    --line-width "$LINE_WIDTH" \
    --expect-records "$EXP_RECORDS" \
    --expect-bases   "$EXP_BASES" 2>&1 | tee -a "$NCRNA_LOG_FILE"

  log "replicate ${rep}: sha256 $(sha256sum "$out" | cut -d' ' -f1)"
  log "replicate ${rep}: md5    $(md5sum "$out" | cut -d' ' -f1)"
  log "replicate ${rep}: bytes  $(stat -c%s "$out")  mode $(stat -c%a "$out")"

  exec {lockfd}>&-
  rm -f "$lock"
done

log "done"
